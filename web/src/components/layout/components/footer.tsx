import { Link } from '@tanstack/react-router'
import { Fragment, useMemo } from 'react'
import { useTranslation } from 'react-i18next'

import { useStatus } from '@/hooks/use-status'
import { useSystemConfig } from '@/hooks/use-system-config'
import { cn } from '@/lib/utils'

import { Container } from './container'
import { SiteContactDetails, SiteSocialLinks } from './site-contact'

interface FooterLink {
  text: string
  href: string
}

interface FooterColumnProps {
  title: string
  links: FooterLink[]
}

interface FooterProps {
  logo?: string
  name?: string
  columns?: FooterColumnProps[]
  copyright?: string
  className?: string
}

function FooterLinkItem(props: { link: FooterLink }) {
  const { t } = useTranslation()
  const isExternal = props.link.href.startsWith('http')
  const label = t(props.link.text)

  if (isExternal) {
    return (
      <a
        href={props.link.href}
        target='_blank'
        rel='noopener noreferrer'
        className='text-muted-foreground hover:text-foreground text-sm transition-colors duration-200'
      >
        {label}
      </a>
    )
  }

  return (
    <Link
      to={props.link.href}
      className='text-muted-foreground hover:text-foreground text-sm transition-colors duration-200'
    >
      {label}
    </Link>
  )
}

// Renders User Agreement / Privacy Policy links inline with the parent's
// copyright row when either is configured in System Settings → Site. Emits
// fragmented siblings so the parent flex container's gap controls spacing.
function LegalLinks(props: { leadingSeparator?: boolean }) {
  const { t } = useTranslation()
  const { status } = useStatus()
  const items: { key: string; label: string; href: string }[] = []
  if (status?.user_agreement_enabled) {
    items.push({
      key: 'user-agreement',
      label: t('User Agreement'),
      href: '/user-agreement',
    })
  }
  if (status?.privacy_policy_enabled) {
    items.push({
      key: 'privacy-policy',
      label: t('Privacy Policy'),
      href: '/privacy-policy',
    })
  }
  if (items.length === 0) {
    return null
  }
  return (
    <>
      {items.map((item, index) => (
        <Fragment key={item.key}>
          {(props.leadingSeparator || index > 0) && (
            <span aria-hidden='true' className='text-muted-foreground/40'>
              ·
            </span>
          )}
          <Link
            to={item.href}
            className='hover:text-foreground transition-colors duration-200'
          >
            {item.label}
          </Link>
        </Fragment>
      ))}
    </>
  )
}

// 上游署名与协议声明：AGENTS.md「Protected project information」保护信息，
// 其中的项目/组织标识不得删除或替换。这里只改展示形式：压成一句感谢声明，
// 去掉 github.com 外链（国内不可访问），由品牌区放到最后一行。
function ProjectAttribution(props: { inline?: boolean; className?: string }) {
  const { t } = useTranslation()
  const currentYear = new Date().getFullYear()
  const content = (
    <span
      className={cn(
        'text-muted-foreground/20 text-[11px] leading-relaxed',
        props.className
      )}
    >
      {t('footer.projectCredit', { year: currentYear })}
    </span>
  )
  if (props.inline) {
    return content
  }
  return <div className='mt-1.5'>{content}</div>
}

// 备案号：法定公示信息，由管理员在「业务设置 → 站点 → 系统信息」配置，
// 未配置时不渲染。
function IcpNotice(props: { icp?: string; className?: string }) {
  if (!props.icp) return null
  return (
    <a
      href='https://beian.miit.gov.cn/'
      target='_blank'
      rel='noopener noreferrer'
      className={cn('hover:text-foreground transition-colors', props.className)}
    >
      {props.icp}
    </a>
  )
}

